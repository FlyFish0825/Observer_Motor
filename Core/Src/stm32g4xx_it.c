/** @brief GPIO外部中断回调：PC10按下启动开环，PC11按下停止并复位FOC状态机。 */
void              HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  switch (GPIO_Pin) {
  case GPIO_PIN_10:
  HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_6);
  foc_motor_state = FOC_MOTOR_OPEN_LOOP;
  FOC_PWM_Start();
    break;
  case GPIO_PIN_11:
  HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_6);
  foc_motor_state = FOC_MOTOR_IDLE;
  FOC_PWM_Stop();
    break;
  case GPIO_PIN_13:


    break;
  }




}
